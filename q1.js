// Função para imprimir o quadrado de um número
function imprimeQuadradoDe(num) {
    console.log(num * num);
}

// Função de soma (escolhendo uma versão da função soma)
function soma(a, b) {
    return a + b;
}

// Função de saudação
function saudacao() {
    console.log("Olá, meu amigo!");
}

// Chamada das funções
saudacao();
imprimeQuadradoDe(4); // Exemplo de uso da função imprimeQuadradoDe

// Utilizando a função soma
let resultado = soma(2, 3);
console.log(resultado); // Exibe a soma de 2 e 3
